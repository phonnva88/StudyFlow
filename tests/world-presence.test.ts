import {test} from 'node:test';
import assert from 'node:assert/strict';
import {ConnectionState, RoomEvent, type RemoteParticipant} from 'livekit-client';
import {createWorldModel, worldPresence} from '../src/lib/world-presence';
import {AVATAR_COLORS, SPAWN} from '../src/lib/world';

test('world presence throttles motion, trusts transport identity, expires peers and cleans up', async t => {
  const original = Object.getOwnPropertyDescriptor(globalThis, 'document');
  const document = Object.assign(new EventTarget(), {hidden: false});
  Object.defineProperty(globalThis, 'document', {configurable: true, value: document});
  t.after(() => { if (original) Object.defineProperty(globalThis, 'document', original); else Reflect.deleteProperty(globalThis, 'document'); });
  t.mock.timers.enable({apis: ['setInterval']});
  let now = 1000;
  t.mock.method(performance, 'now', () => now);
  const model = createWorldModel();
  const presence = worldPresence(model, () => {});
  t.after(() => presence.dispose());
  const room = presence.room;
  const messages: Uint8Array[] = [];
  t.mock.method(room.localParticipant, 'publishData', async (data: Uint8Array) => { messages.push(data); });
  t.mock.method(room, 'disconnect', async () => {});
  t.mock.method(room, 'connect', async () => { room.state = ConnectionState.Connected; });
  await presence.connect('wss://test.livekit.cloud', 'token');
  assert.equal(messages.length, 1);
  model.local.animation = 'walking';
  for (let i = 0; i < 10; i++) { now += 100; model.local.x += 1; t.mock.timers.tick(100); }
  assert.equal(messages.length, 11);
  const participant = {identity: 'transport-id', name: 'Ada', metadata: JSON.stringify({worldAvatar: AVATAR_COLORS[0]})} as RemoteParticipant;
  const send = (data: unknown) => room.emit(RoomEvent.DataReceived, new TextEncoder().encode(JSON.stringify(data)), participant, undefined, 'studyflow.world.position');
  send({...SPAWN, direction: 'up', animation: 'idle', seq: 1, playerId: 'forged', nickname: '<script>'});
  assert.equal(model.peers.get('transport-id')?.nickname, 'Ada');
  assert.ok(!model.peers.has('forged'));
  now += 100;
  send({...SPAWN, x: -100, direction: 'up', animation: 'idle', seq: 2});
  assert.equal(model.peers.get('transport-id')?.seq, 1);
  now += 100;
  send({...SPAWN, direction: 'up', animation: 'idle', seq: 0});
  assert.equal(model.peers.get('transport-id')?.seq, 1);
  room.emit(RoomEvent.ParticipantDisconnected, participant);
  assert.equal(model.peers.size, 0);
  now += 100; send({...SPAWN, direction: 'down', animation: 'idle', seq: 3});
  now += 10001; t.mock.timers.tick(100);
  assert.equal(model.peers.size, 0);
  document.hidden = true; document.dispatchEvent(new Event('visibilitychange'));
  assert.equal(JSON.parse(new TextDecoder().decode(messages.at(-1))).animation, 'idle');
  presence.dispose();
  const sent = messages.length;
  now += 10000; t.mock.timers.tick(10000);
  assert.equal(messages.length, sent);
});
